#!/usr/bin/env bash

RED=$(tput setaf 1)
GREEN=$(tput setaf 2)
YELLOW=$(tput setaf 3)
BLUE=$(tput setaf 4)
BOLD=$(tput bold)
RESET=$(tput sgr0)

printf '%s\n' "${BLUE}Starting system update...${RESET}"
printf '%s\n' "${GREEN}Starting system update...${RESET}"
printf '%s\n' "${YELLOW}Starting system update...${RESET}"
printf '%s\n' "${RED}Starting system update...${RESET}"
printf '%s\n' "${BOLD}Starting system update...${RESET}"
